const textos = { pt }

export function t(chave, vars = {}, idioma = 'pt') {
  const modelo = (textos[idioma] ?? pt)[chave]
  if (modelo === undefined) throw new Error(`texto ausente: ${chave}`)
  return modelo.replace(/\{(\w+)\}/g, (_, nome) => (nome in vars ? String(vars[nome]) : `{${nome}}`))
}
